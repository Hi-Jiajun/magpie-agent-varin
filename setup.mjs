#!/usr/bin/env node
// Fill varin-provider.js from this computer's Varin install.
//
//   node setup.mjs
//
// Not required: with the file left empty the plugin writes only `defaultModel`,
// which is already correct when Varin's default channel is the Magpie one (the
// normal case). Running this additionally keeps `defaultProvider` pointed at the
// right channel when you pick a model, which matters if your Varin has more than
// one channel and the default is another vendor's.
//
// This rewrites a file that is published. Check `git diff` before publishing.

import { readFile, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import path from 'node:path'

const modelsPath = path.join(homedir(), '.config', 'varin', 'models.json')

let data
try {
  data = JSON.parse(await readFile(modelsPath, 'utf8'))
} catch (error) {
  console.error(`Could not read ${modelsPath}: ${error.message}`)
  console.error('Varin must have run at least once on this computer.')
  process.exit(1)
}

const channels = data.channels ?? []

// The channel that reaches this computer's magpie gateway, whatever its id.
const isGateway = (channel) => {
  try {
    const url = new URL(channel.baseUrl ?? '')
    const local = ['127.0.0.1', 'localhost', '::1', '[::1]'].includes(url.hostname)
    return local && url.port === '3425'
  } catch {
    return false
  }
}

const channel = channels.find(isGateway) ?? (channels.length === 1 ? channels[0] : undefined)
if (!channel) {
  console.error(`No Magpie channel found among ${channels.length} in ${modelsPath}.`)
  console.error('Add one in Varin (Settings → models) pointing at magpie, then run this again.')
  process.exit(1)
}

const ids = (channel.models ?? []).map((model) => model.id).filter(Boolean)

const file = `// Generated by ./setup.mjs from ${modelsPath}.
// Do not edit by hand; run the script again instead.

export const PROVIDER_ID = ${JSON.stringify(channel.id)}

export const KNOWN_MODELS = new Set([
${ids.sort().map((id) => `  ${JSON.stringify(id)},`).join('\n')}
])
`

await writeFile(new URL('./varin-provider.js', import.meta.url), file)
console.log(`Wrote varin-provider.js: channel ${channel.name} (${channel.id}), ${ids.length} models`)
